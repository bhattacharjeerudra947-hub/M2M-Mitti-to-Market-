/** Map browser speech-recognition language tags to internal codes */
export function normaliseLangCode(raw) {
  if (!raw) return 'en';
  const base = raw.split('-')[0].toLowerCase();
  const map = {
    as:'as', bn:'bn', brx:'brx', doi:'doi', gu:'gu', hi:'hi', kn:'kn',
    ks:'ks', kok:'kok', mai:'mai', ml:'ml', mni:'mni', mr:'mr', ne:'ne',
    or:'or', pa:'pa', sa:'sa', sat:'sat', sd:'sd', ta:'ta', te:'te', ur:'ur',
  };
  return map[base] || 'en';
}

/** Return language object by code */
export function getLanguageByCode(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

